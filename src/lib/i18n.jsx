// Helper: translated option value
export const useOption = () => {
  const { t } = useLanguage();
  return (val) => {
    if (val == null) return val;
    const tr = t(`options.${String(val)}`);
    return tr === String(val) ? val : tr;
  };
};

// Currency: stored prices are in EUR (base). Display currency changes by language.
const CURRENCY_BY_LANG = { en: "EUR", ro: "RON", fr: "EUR" };
const LOCALE_BY_LANG = { en: "en-IE", ro: "ro-RO", fr: "fr-FR" };
const EUR_RATE = { EUR: 1, RON: 4.97 };

export const useFormatPrice = () => {
  const { lang } = useLanguage();
  return useCallback((price) => {
    if (price == null || price === "") return "";
    const currency = CURRENCY_BY_LANG[lang] || "EUR";
    const locale = LOCALE_BY_LANG[lang] || "en-IE";
    const rate = EUR_RATE[currency] ?? 1;
    const converted = Number(price) * rate;
    if (isNaN(converted)) return "";
    return new Intl.NumberFormat(locale, {
      style: "currency",
      currency,
      maximumFractionDigits: 0,
    }).format(converted);
  }, [lang]);
};
